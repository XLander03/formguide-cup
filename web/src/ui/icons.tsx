const BARS = [16, 28, 12, 40, 24, 34, 14, 38, 20, 30, 12];

export function Waveform({ compact = false }: { compact?: boolean }) {
  return (
    <div
      className={`flex items-center gap-1.5 ${compact ? 'h-12' : 'h-36'}`}
      aria-label="Animated voice waveform"
    >
      {BARS.map((bar, index) => (
        <span
          key={index}
          className={`fg-wave w-1.5 ${index % 3 === 0 ? 'bg-primary' : 'bg-background/45'}`}
          style={{
            height: `${compact ? Math.max(8, bar * 0.65) : bar * 2}px`,
            animationDelay: `${index * 70}ms`,
          }}
        />
      ))}
    </div>
  );
}
